# Harmless loopback only. No runner entry point, app, MSI, elevation or process-stop helper.
$ErrorActionPreference = 'Stop'
$runner = Join-Path $PSScriptRoot 'verify-installed-updater-smoke.ps1'
$tokens = $null
$errors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile($runner, [ref]$tokens, [ref]$errors)
if ($errors.Count) { throw ($errors | Out-String) }
foreach ($definition in $ast.FindAll({ param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] }, $false)) {
    if ($definition.Name -in @('Start-ManifestServer', 'Send-SmokeResponse', 'Write-Utf8', 'Assert-True')) {
        . ([scriptblock]::Create($definition.Extent.Text))
    }
}
function Check($Condition, $Message) { if (-not $Condition) { throw $Message } }
$fixture = Join-Path ([IO.Path]::GetTempPath()) ('updater-http-test-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $fixture | Out-Null
$WorkDir = $fixture
$script:checks = $null
$reservation = New-Object Net.Sockets.TcpListener([Net.IPAddress]::Loopback, 0)
$reservation.Start()
$ManifestPort = $reservation.LocalEndpoint.Port
$reservation.Stop()
$binary = Join-Path $fixture 'large.bin'
[IO.File]::WriteAllBytes($binary, (New-Object byte[] (16 * 1024 * 1024)))
$signature = Join-Path $fixture 'fixture.sig'
[IO.File]::WriteAllText($signature, 'fixture only, not a signature')

# Capture the exact standalone script generated by the production launcher.
function Start-Process($FilePath, $WindowStyle, [switch]$PassThru, $ArgumentList) {
    Check ($WindowStyle -eq 'Hidden') 'Server child must be hidden.'
    $script:encodedServer = ($ArgumentList -split ' ')[-1]
    [pscustomobject]@{ Id = 0 }
}
function Wait-Until { $true }
Start-ManifestServer $binary $signature '0.0.2'
$server = [Text.Encoding]::Unicode.GetString([Convert]::FromBase64String($script:encodedServer))
Check ($server.Contains('while ($true) {') -and $server.Contains('$ctx = $listener.GetContext()')) 'Standalone server harness changed; update the bounded fixture explicitly.'
# Bound only request count and accept wait. The serialized response code is untouched.
$server = $server.Replace('while ($true) {', 'foreach ($fixtureRequest in 1..4) {')
$server = $server.Replace('$ctx = $listener.GetContext()', '$pending = $listener.GetContextAsync(); if (-not $pending.Wait(10000)) { throw "Fixture accept timed out" }; $ctx = $pending.Result')
$server = 'try {' + "`n" + $server + "`n" + '} finally { if ($listener) { $listener.Close() } }'
$encoded = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($server))
$child = New-Object Diagnostics.Process
$child.StartInfo.FileName = (Get-Command powershell.exe).Source
$child.StartInfo.Arguments = "-NoProfile -ExecutionPolicy Bypass -EncodedCommand $encoded"
$child.StartInfo.UseShellExecute = $false
$child.StartInfo.CreateNoWindow = $true
$child.StartInfo.RedirectStandardOutput = $true
$child.StartInfo.RedirectStandardError = $true
Check ($child.Start()) 'Could not start the finite loopback fixture.'
try {
    # Wait for the listener without consuming one of its four HTTP requests.
    $ready = $false
    $deadline = (Get-Date).AddSeconds(5)
    do {
        $probe = New-Object Net.Sockets.TcpClient
        try { $probe.Connect('127.0.0.1', $ManifestPort); $ready = $true } catch { Start-Sleep -Milliseconds 50 } finally { $probe.Dispose() }
    } while (-not $ready -and -not $child.HasExited -and (Get-Date) -lt $deadline)
    if (-not $ready) { throw "Loopback listener did not start: $($child.StandardError.ReadToEnd())" }
    $baseUrl = "http://127.0.0.1:$ManifestPort"
    $response = Invoke-WebRequest -Uri "$baseUrl/latest.json" -UseBasicParsing -TimeoutSec 5
    Check ($response.StatusCode -eq 200 -and ($response.Content | ConvertFrom-Json).version -eq '0.0.2') 'Serialized server did not return the fixture manifest.'
    $notFound = 0
    try { Invoke-WebRequest -Uri "$baseUrl/missing?private=value" -UseBasicParsing -TimeoutSec 5 | Out-Null } catch {
        if ($_.Exception.Response) { $notFound = [int]$_.Exception.Response.StatusCode } else { throw }
    }
    Check ($notFound -eq 404) 'Serialized server did not return HTTP 404.'

    # Reset the client during a real large response. The small receive window prevents buffering it all.
    $client = New-Object Net.Sockets.TcpClient
    try {
        $client.ReceiveBufferSize = 1024
        $client.Connect('127.0.0.1', $ManifestPort)
        $stream = $client.GetStream()
        $stream.ReadTimeout = 5000
        $request = [Text.Encoding]::ASCII.GetBytes("GET /large.bin HTTP/1.1`r`nHost: 127.0.0.1`r`nConnection: close`r`n`r`n")
        $stream.Write($request, 0, $request.Length)
        $headers = ''
        while (-not $headers.EndsWith("`r`n`r`n") -and $headers.Length -lt 4096) {
            $next = $stream.ReadByte()
            if ($next -lt 0) { throw 'Interrupted-response fixture received no headers.' }
            $headers += [char]$next
        }
        Check ($headers.StartsWith('HTTP/1.1 200') -and $headers.EndsWith("`r`n`r`n")) 'Large-response fixture did not reach its body.'
        $client.Client.LingerState = New-Object Net.Sockets.LingerOption($true, 0)
    } finally { $client.Dispose() }
    $response = Invoke-WebRequest -Uri "$baseUrl/latest.json" -UseBasicParsing -TimeoutSec 5
    Check ($response.StatusCode -eq 200) 'Server did not handle another request after client interruption.'
} finally {
    # The finite fixture exits on its own, including a bounded accept timeout after a failed test.
    if (-not $child.WaitForExit(15000)) { throw "Finite fixture did not exit within its bound. PID $($child.Id), no process was terminated." }
}
$stderr = $child.StandardError.ReadToEnd()
Check ($child.ExitCode -eq 0) "Standalone server failed: $stderr"
$entries = @(Get-Content -LiteralPath $script:requestLog | ForEach-Object { $_ | ConvertFrom-Json })
$results = @($entries | Where-Object { $_.event -eq 'response' })
Check ($results.Count -eq 4) 'Expected four durable response records.'
Check ($results[0].completed -and $results[0].attemptedStatus -eq 200 -and $results[0].bytesWritten -gt 0) 'Real HTTP 200 completion evidence is incorrect.'
Check ($results[1].completed -and $results[1].attemptedStatus -eq 404 -and $results[1].path -eq 'unrecognized') 'Real HTTP 404 evidence is incorrect.'
Check (-not $results[2].completed -and $results[2].error) 'Client reset was reported as a completed response.'
Check ($results[3].completed -and $results[3].attemptedStatus -eq 200) 'Final HTTP completion evidence is missing.'
Write-Host "PASS: actual serialized HttpListener child, HTTP 200/404, client reset and post-reset response. Fixtures: $fixture"
$child.Dispose()
